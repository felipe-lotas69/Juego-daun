const cache = new Map();

function shade(hex, k) {
  const r = Math.min(255, Math.round((((hex >> 16) & 255)) * k));
  const g = Math.min(255, Math.round((((hex >> 8) & 255)) * k));
  const b = Math.min(255, Math.round(((hex & 255)) * k));
  return `rgb(${r},${g},${b})`;
}

/* Returns a canvas of the icon at 1:1; the caller scales it with
   nearest sampling by drawing it larger. */
export function iconCanvas(name, tint = 0xb0b0b0, accent = '#ffcf5e') {
  const key = `${name}:${tint}:${accent}`;
  if (cache.has(key)) return cache.get(key);
  const art = ART[name] || ART.rock;
  const c = document.createElement('canvas');
  c.width = S; c.height = S;
  const g = c.getContext('2d');
  const colors = {
    '#': shade(tint, 0.34),
    '1': shade(tint, 0.6),
    '2': shade(tint, 0.95),
    '3': shade(tint, 1.35),
    '4': accent,
  };
  for (let y = 0; y < S; y++) {
    const row = art[y] || '';
    for (let x = 0; x < S; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      g.fillStyle = colors[ch] || colors['2'];
      g.fillRect(x, y, 1, 1);
    }
  }
  cache.set(key, c);
  if (cache.size > 400) cache.delete(cache.keys().next().value);
  return c;
}

export function drawIcon(ctx, name, x, y, size, tint, accent) {
  const c = iconCanvas(name, tint, accent);
  const s = Math.max(1, Math.round(size / S));
  ctx.drawImage(c, 0, 0, S, S, Math.round(x), Math.round(y), S * s, S * s);
  return S * s;
}

